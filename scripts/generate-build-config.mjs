#!/usr/bin/env node
/**
 * 编译期常量注入脚本
 * 负责检测 Git 仓库环境变量并在编译时将其写死在程序内。
 * 若不存在有效仓库信息，则将自动更新服务标记为未启用 (IS_UPDATER_ENABLED = false)。
 */
import fs from "node:fs";
import path from "node:path";
import { execSync } from "node:child_process";
import { fileURLToPath } from "node:url";
import { createPublicKey } from "node:crypto";
import { resolveServerConfig } from "./resolve-server-config.mjs";

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const rootDir = path.resolve(__dirname, "..");
const desktopSrcDir = path.resolve(rootDir, "apps/desktop/src");

function loadEnvFile(envPath) {
  if (!fs.existsSync(envPath)) return {};
  const content = fs.readFileSync(envPath, "utf-8");
  const env = {};
  for (const line of content.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eqIdx = trimmed.indexOf("=");
    if (eqIdx > 0) {
      const key = trimmed.slice(0, eqIdx).trim();
      let val = trimmed.slice(eqIdx + 1).trim();
      if (
        (val.startsWith('"') && val.endsWith('"')) ||
        (val.startsWith("'") && val.endsWith("'"))
      ) {
        val = val.slice(1, -1);
      }
      env[key] = val;
    }
  }
  return env;
}

function detectGitRemoteRepo() {
  try {
    const output = execSync("git remote get-url origin", {
      cwd: rootDir,
      encoding: "utf-8",
      stdio: ["pipe", "pipe", "ignore"],
    }).trim();
    if (!output) return null;

    // 支持 https://github.com/owner/repo.git 或 git@github.com:owner/repo.git
    const match = output.match(
      /github\.com[/:]([\w.-]+)\/([\w.-]+?)(\.git)?$/i,
    );
    if (match && match[1] && match[2]) {
      return `${match[1]}/${match[2]}`;
    }
  } catch {
    // 忽略 git 探测异常
  }
  return null;
}

function resolveRepo() {
  // 1. 优先读取标准环境变量 (GitHub Actions 会自动注入 GITHUB_REPOSITORY)
  if (
    process.env.GITHUB_REPOSITORY &&
    process.env.GITHUB_REPOSITORY.includes("/")
  ) {
    return process.env.GITHUB_REPOSITORY.trim();
  }

  // 2. 读取根目录 .env
  const localEnv = loadEnvFile(path.join(rootDir, ".env"));
  if (localEnv.GITHUB_REPOSITORY && localEnv.GITHUB_REPOSITORY.includes("/")) {
    return localEnv.GITHUB_REPOSITORY.trim();
  }
  if (
    localEnv.VITE_GITHUB_REPOSITORY &&
    localEnv.VITE_GITHUB_REPOSITORY.includes("/")
  ) {
    return localEnv.VITE_GITHUB_REPOSITORY.trim();
  }

  // 3. 尝试通过当前本地 git remote 探测
  const gitRemote = detectGitRemoteRepo();
  if (gitRemote) {
    return gitRemote;
  }

  return null;
}

function main() {
  const serverConfig = resolveServerConfig();
  if (serverConfig.serverUrl) {
    console.log(
      `[BuildConfig] 🎯 固化服务器地址: ${serverConfig.serverUrl} | 网关: ${serverConfig.gatewayUrl} (来源: ${serverConfig.source})`,
    );
  } else {
    console.log(
      `[BuildConfig] ℹ️ 未指定自定义服务器地址，将默认连接本地开发/自宿主服务 (http://localhost:3001)`,
    );
  }
  const repoString = resolveRepo();
  let isUpdaterEnabled = false;
  let repoOwner = "";
  let repoName = "";
  let repoFullName = "";
  const publicKey = process.env.UPDATE_SIGNING_PUBLIC_KEY_BASE64?.trim() || "";
  let validPublicKey = false;
  if (publicKey) {
    try {
      validPublicKey =
        createPublicKey({
          key: Buffer.from(publicKey, "base64"),
          format: "der",
          type: "spki",
        }).asymmetricKeyType === "ed25519";
    } catch {
      validPublicKey = false;
    }
  }

  if (repoString && repoString.includes("/")) {
    const [owner, name] = repoString.split("/");
    if (owner && name) {
      isUpdaterEnabled = validPublicKey;
      repoOwner = owner.trim();
      repoName = name.replace(/\.git$/i, "").trim();
      repoFullName = `${repoOwner}/${repoName}`;
      console.log(
        `[BuildConfig] GitHub 仓库: "${repoFullName}"；更新签名公钥${validPublicKey ? "有效，更新已启用" : "缺失或无效，更新已禁用"}。`,
      );
    }
  }

  if (!repoFullName) {
    console.log(
      `⚠️ [BuildConfig] 未检测到有效的 GitHub 仓库信息 (未设置 GITHUB_REPOSITORY 且无有效 GitHub remote)，自动更新服务将不生效 (IS_UPDATER_ENABLED = false)。`,
    );
  }

  const primaryProxy = "https://v6.gh-proxy.org/";
  const backupProxy = "https://gh-proxy.com/";

  const content = `/* AUTO-GENERATED BY scripts/generate-build-config.mjs - DO NOT EDIT MANUALLY */
/**
 * 编译期写死在客户端内部的固化配置
 */
export const BUILD_CONFIG = {
  /** 编译期固化的服务器 API 地址 (若未指定则为空字符串，客户端默认连接 localhost:3001) */
  DEFAULT_SERVER_URL: ${JSON.stringify(serverConfig.serverUrl || "")},
  /** 编译期固化的公开 Web 站点域名 (用于邀请链接/外部分享) */
  DEFAULT_WEB_URL: ${JSON.stringify(serverConfig.webUrl || serverConfig.serverUrl || "")},
  /** 编译期固化的 WebSocket Gateway 地址 */
  DEFAULT_GATEWAY_URL: ${JSON.stringify(serverConfig.gatewayUrl || "")},
  /** 编译期固化的 LiveKit SFU 媒体服务地址 */
  DEFAULT_LIVEKIT_URL: ${JSON.stringify(serverConfig.livekitUrl || "")},
  /** Installed host retains its media engine across Web updates. */
  DEFAULT_VOICE_ENGINE: ${JSON.stringify(serverConfig.voiceEngine)},
  /** 固化服务器配置来源 */
  SERVER_CONFIG_SOURCE: ${JSON.stringify(serverConfig.source)},
  /** 是否启用了更新检测服务 (build 时未检测到仓库信息则为 false，此时不进行更新检测) */
  IS_UPDATER_ENABLED: ${isUpdaterEnabled},
  /** GitHub 仓库拥有者 (Owner) */
  REPO_OWNER: ${JSON.stringify(repoOwner)},
  /** GitHub 仓库名 (Repo) */
  REPO_NAME: ${JSON.stringify(repoName)},
  /** GitHub 仓库全称 (owner/repo) */
  REPO_FULL_NAME: ${JSON.stringify(repoFullName)},
  /** Ed25519 public key in DER/SPKI base64; absent keys disable updates. */
  UPDATE_SIGNING_PUBLIC_KEY_BASE64: ${JSON.stringify(validPublicKey ? publicKey : "")},
  /** 编译时间戳 (ISO 8601) */
  BUILD_TIME: ${JSON.stringify(new Date().toISOString())},
  /** 默认首选 gh-proxy 加速代理 (优先使用 v6.gh-proxy.org) */
  PRIMARY_GH_PROXY: ${JSON.stringify(primaryProxy)},
  /** 备用 gh-proxy 加速代理 (gh-proxy.com) */
  BACKUP_GH_PROXY: ${JSON.stringify(backupProxy)},
} as const;

export type BuildConfig = typeof BUILD_CONFIG;
`;

  if (!fs.existsSync(desktopSrcDir)) {
    fs.mkdirSync(desktopSrcDir, { recursive: true });
  }

  const targetFile = path.join(desktopSrcDir, "build-config.ts");
  if (fs.existsSync(targetFile)) {
    const existing = fs.readFileSync(targetFile, "utf-8");
    // 去除 BUILD_TIME 对比避免每次空跑都触发重新编译
    const stripBuildTime = (str) => str.replace(/BUILD_TIME: ".*?",/, "");
    if (stripBuildTime(existing) === stripBuildTime(content)) {
      console.log(`ℹ️ [BuildConfig] ${targetFile} 内容未变，跳过覆写。`);
      return;
    }
  }

  fs.writeFileSync(targetFile, content, "utf-8");
  console.log(`💾 [BuildConfig] 已生成编译期固化配置至: ${targetFile}`);
}

main();
